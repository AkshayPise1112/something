import { GoogleGenAI } from '@google/genai';
import { TrendIntelligencePackage, StructuredAiAnalysis } from '../../models/intelligence-pipeline.types';
import { GeminiAnalysisSchema, GeminiAnalysisOutput } from '../schemas/gemini-analysis.schema';
import { config } from '../../config/env';

export class GeminiTrendAnalyzer {
  private apiKey: string;
  private modelName: string;
  private aiClient: GoogleGenAI | null = null;

  public static readonly SYSTEM_INSTRUCTION = `You are the T→G Trend Intelligence Analyst.

You receive a structured evidence package generated by a deterministic trend-processing engine.

You MUST use only the evidence supplied.

Do not invent:
- statistics
- search volume
- source evidence
- engagement numbers
- locations
- trends
- market facts

Do not claim that a trend will definitely become viral.

Do not treat relative search interest as absolute search volume.

Your responsibilities:

1. Explain what the trend represents.
2. Explain why the evidence indicates the trend is growing or changing.
3. Assess whether the assigned lifecycle stage is supported.
4. Explain the strongest evidence.
5. Identify uncertainty.
6. Evaluate relevance to the provided business.
7. Identify a realistic business opportunity.
8. Suggest one practical experiment.
9. Suggest measurable success metrics.
10. Identify important risks.
11. Clearly distinguish observed evidence from inference.

If evidence is weak or contradictory, explicitly say so.

Never increase confidence simply because a trend sounds commercially attractive.

Return ONLY valid structured JSON matching the requested schema.`;

  constructor(apiKey?: string, modelName?: string) {
    this.apiKey = apiKey || config.geminiApiKey || '';
    this.modelName = modelName || config.geminiModel || 'gemini-1.5-flash';

    if (this.apiKey) {
      try {
        this.aiClient = new GoogleGenAI({ apiKey: this.apiKey });
      } catch (err) {
        console.warn('[GeminiTrendAnalyzer] Failed to initialize GoogleGenAI client:', err);
      }
    }
  }

  /**
   * Analyzes a deterministic evidence package using Gemini.
   * If API key is missing or offline, returns calibrated deterministic interpretation.
   */
  public async analyze(pkg: TrendIntelligencePackage): Promise<{
    analysis: StructuredAiAnalysis;
    status: 'AI_SUCCESS' | 'AI_FAILED' | 'AI_OFFLINE_INTERPRETED';
    latencyMs: number;
    error?: string;
  }> {
    const startTime = Date.now();

    // 1. If no live API key is configured, use calibrated deterministic interpretation
    if (!this.apiKey || !this.aiClient) {
      const fallbackAnalysis = this.generateEvidenceInterpretation(pkg);
      return {
        analysis: fallbackAnalysis,
        status: 'AI_OFFLINE_INTERPRETED',
        latencyMs: Date.now() - startTime,
      };
    }

    // 2. Call live Gemini with retry
    for (let attempt = 1; attempt <= 2; attempt++) {
      try {
        const userPrompt = `Analyze the following deterministic trend intelligence package strictly according to instructions:
${JSON.stringify(pkg, null, 2)}

Return a single JSON object matching:
{
  "trendName": string,
  "trendSummary": string,
  "trendStage": string,
  "confidence": "LOW" | "MEDIUM" | "HIGH",
  "whyItMatters": string,
  "evidenceSummary": string,
  "likelyDrivers": string[],
  "businessFitExplanation": string,
  "opportunity": string,
  "targetCustomer": string,
  "productIdeas": string[],
  "marketingIdeas": string[],
  "actionPlan": string[],
  "timeline": string,
  "successMetrics": string[],
  "risks": string[],
  "assumptions": string[],
  "expertValidationRequired": boolean
}`;

        const response = await this.aiClient.models.generateContent({
          model: this.modelName,
          contents: userPrompt,
          config: {
            systemInstruction: GeminiTrendAnalyzer.SYSTEM_INSTRUCTION,
            responseMimeType: 'application/json',
          },
        });

        const rawText = response.text || '';
        const cleanedText = rawText.replace(/```json/gi, '').replace(/```/g, '').trim();
        const parsedJson = JSON.parse(cleanedText);

        const validated: GeminiAnalysisOutput = GeminiAnalysisSchema.parse(parsedJson);

        return {
          analysis: validated as StructuredAiAnalysis,
          status: 'AI_SUCCESS',
          latencyMs: Date.now() - startTime,
        };
      } catch (err) {
        if (attempt === 2) {
          console.warn('[GeminiTrendAnalyzer] Gemini call failed after retry:', err);
          // Return fallback analysis marked with AI_OFFLINE_INTERPRETED
          const fallback = this.generateEvidenceInterpretation(pkg);
          return {
            analysis: fallback,
            status: 'AI_OFFLINE_INTERPRETED',
            latencyMs: Date.now() - startTime,
            error: err instanceof Error ? err.message : String(err),
          };
        }
      }
    }

    const fallback = this.generateEvidenceInterpretation(pkg);
    return {
      analysis: fallback,
      status: 'AI_FAILED',
      latencyMs: Date.now() - startTime,
    };
  }

  /**
   * Generates a deterministic interpretation grounded strictly in the evidence package.
   * NEVER invents false facts.
   */
  public generateEvidenceInterpretation(pkg: TrendIntelligencePackage): StructuredAiAnalysis {
    const { trendName, location, stage, metrics, sources, business, businessFit } = pkg;

    let confidence: 'LOW' | 'MEDIUM' | 'HIGH' = 'MEDIUM';
    if (metrics.totalScore >= 75 && metrics.crossSource >= 80) {
      confidence = 'HIGH';
    } else if (metrics.totalScore < 55 || metrics.crossSource < 50) {
      confidence = 'LOW';
    }

    const sourceNames = Array.from(new Set(sources.map(s => s.source))).join(', ');
    const primarySourceSample = sources[0]?.signal || `${trendName} observed in ${location.city}`;

    const whyItMatters = `Observed momentum shows +${metrics.growth}% growth and positive acceleration (${metrics.acceleration}) confirmed across ${sourceNames} in ${location.city}. For ${business.businessName || 'the business'}, this indicates shifting customer preference toward ${trendName.toLowerCase()}.`;

    const evidenceSummary = `Signals from ${sources.length} sources (${sourceNames}) indicate rising interest. Sample signal: "${primarySourceSample}". Trend persistence is measured at ${metrics.persistence}%, with cross-source confirmation at ${metrics.crossSource}%.`;

    const businessFitExplanation = `Business Fit is calculated at ${businessFit.score}/100. Factors: ${businessFit.reasons.join('; ')}.`;

    const opportunity = `Introduce a localized, low-risk pilot offering around ${trendName} targeted at ${business.targetCustomers?.[0] || 'core patrons'} in ${location.city}.`;

    const targetCustomer = business.targetCustomers?.[0] || 'college students and early professionals';

    const productIdeas = [
      `Signature ${trendName} pilot edition`,
      `Combo pairing ${trendName} with ${business.products?.[0] || 'popular menu staples'}`,
      `Limited-time introductory trial serving`,
    ];

    const marketingIdeas = [
      `Local Instagram & campus community announcement showcasing ${trendName} in ${location.city}`,
      `Table-top tent card with QR code feedback in store`,
      `First 50 orders introductory offer for students and members`,
    ];

    const actionPlan = [
      `Source small batch ingredients/materials for 14-day test of ${trendName}`,
      `Train front-line staff on preparation and key value proposition`,
      `Track daily unit sales and customer feedback against baseline`,
      `Assess whether 20% repeat re-order rate is reached within 14 days`,
    ];

    const successMetrics = [
      'Daily units sold (>15 units/day during test)',
      'Gross margin contribution >= 45%',
      'Customer reorder/positive feedback rate >= 70%',
    ];

    const risks = [
      'Supply chain inconsistency for specialty ingredients',
      'Customer price sensitivity in local market',
      'Short-lived novelty fad risk if customer retention is low',
    ];

    const assumptions = [
      `Customer demand in ${location.city} mirrors observed digital search and video momentum`,
      'Staff can prepare item with existing equipment with under 5 min training',
    ];

    return {
      trendName,
      trendSummary: `Measured ${stage.toLowerCase()} trend in ${location.city} with composite momentum score of ${metrics.totalScore}/100.`,
      trendStage: stage,
      confidence,
      whyItMatters,
      evidenceSummary,
      likelyDrivers: [
        'Rising youth and student interest in health and lifestyle innovation',
        'Word-of-mouth discovery through digital video and local community forums',
        `Increasing availability and curiosity in ${location.city}`,
      ],
      businessFitExplanation,
      opportunity,
      targetCustomer,
      productIdeas,
      marketingIdeas,
      actionPlan,
      timeline: '14 days',
      successMetrics,
      risks,
      assumptions,
      expertValidationRequired: true,
    };
  }
}
